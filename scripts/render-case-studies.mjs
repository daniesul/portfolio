// Renders the case-study gallery on /demand-revenue-marketing from data/case-studies.json.
// Usage: node scripts/render-case-studies.mjs
// The output is static HTML written between the two marker comments in the page, so it stays
// readable without JavaScript and the site keeps its no-build-step deploy. Re-run after editing the JSON.
//
// Fields per entry: id, company, category, title, description, href, cta (optional),
// result (optional): { value, label } for a metric OR { text } for a qualitative outcome. Omit it if there is none.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const page = new URL('demand-revenue-marketing.html', root);
const studies = JSON.parse(readFileSync(new URL('data/case-studies.json', root), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const card = (c) => {
  const tid = `t-${c.id}`;
  const r = c.result;
  const result = !r ? '' : r.value
    ? `\n<p class="cs-result"><strong>${esc(r.value)}</strong><span>${esc(r.label)}</span></p>`
    : `\n<p class="cs-result cs-result--text"><span>${esc(r.text)}</span></p>`;
  return `<li>
<article class="cs" aria-labelledby="${tid}">
<p class="mono cs-meta"><strong>${esc(c.company)}</strong><span class="muted">${esc(c.category)}</span></p>
<h3 class="cs-title" id="${tid}">${esc(c.title)}</h3>
<p class="cs-desc">${esc(c.description)}</p>${result}
<a class="cs-link" href="${esc(c.href)}">${esc(c.cta || 'View case study')} <span aria-hidden="true">→</span><span class="vh">: ${esc(c.title)}</span></a>
</article>
</li>`;
};

const start = '<!-- case-studies:start (generated by scripts/render-case-studies.mjs from data/case-studies.json; do not edit by hand) -->';
const end = '<!-- case-studies:end -->';
const html = readFileSync(page, 'utf8');
const a = html.indexOf('<!-- case-studies:start');
const b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error('Markers not found in demand-revenue-marketing.html');
const out = `${start}\n${studies.map(card).join('\n')}\n`;
writeFileSync(page, html.slice(0, a) + out + html.slice(b));
console.log(`Rendered ${studies.length} case stud${studies.length === 1 ? 'y' : 'ies'}.`);
