// Renders the case-study gallery on /demand-revenue-marketing from data/case-studies.json.
// Usage: node scripts/render-case-studies.mjs
// The output is static HTML written between the two marker comments in the page, so it stays
// readable without JavaScript and the site keeps its no-build-step deploy. Re-run after editing the JSON.
//
// Fields per entry: id, company, category, title, description, href, cta (optional),
// tag (optional pill text), result (optional): { value, label } for a metric OR { text } for a qualitative outcome. Omit it if there is none.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('../', import.meta.url);
const page = new URL('demand-revenue-marketing.html', root);
const studies = JSON.parse(readFileSync(new URL('data/case-studies.json', root), 'utf8'));
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

const SECTION_TAG = 'Demand & Revenue Marketing'; // pill on each card; override per entry with a "tag" field
const card = (c, i) => {
  const tid = `t-${c.id}`;
  const r = c.result;
  const kpi = !r ? '' : r.value
    ? `\n<ul class="kpi-row" aria-label="Featured metric">\n<li><strong>${esc(r.value)}</strong><span>${esc(r.label)}</span></li>\n</ul>`
    : `\n<ul class="kpi-row" aria-label="Featured outcome">\n<li><span>${esc(r.text)}</span></li>\n</ul>`;
  return `<article class="card" aria-labelledby="${tid}">
<div class="card-top"><span class="mono muted">Case study ${String(i + 1).padStart(2, '0')}</span><span class="tag"><span class="dot"></span>${esc(c.tag || SECTION_TAG)}</span></div>
<p class="ctype">Case Studies &amp; Execution</p>
<h3 class="card-title" id="${tid}">${esc(c.title)}</h3>
<dl class="meta">
<div><dt class="mono">Company</dt><dd>${esc(c.company)}</dd></div>
<div><dt class="mono">Category</dt><dd>${esc(c.category)}</dd></div>
</dl>
<p class="overview">${esc(c.description)}</p>${kpi}
<div><a class="btn" href="${esc(c.href)}">${esc(c.cta || 'View Case Study')} <span aria-hidden="true">→</span></a></div>
</article>`;
};

const start = '<!-- case-studies:start (generated by scripts/render-case-studies.mjs from data/case-studies.json; do not edit by hand) -->';
const end = '<!-- case-studies:end -->';
const html = readFileSync(page, 'utf8');
const a = html.indexOf('<!-- case-studies:start');
const b = html.indexOf(end);
if (a < 0 || b < 0) throw new Error('Markers not found in demand-revenue-marketing.html');
const out = `${start}\n${studies.map(card).join('\n\n')}\n`;
writeFileSync(page, html.slice(0, a) + out + html.slice(b));
console.log(`Rendered ${studies.length} case stud${studies.length === 1 ? 'y' : 'ies'}.`);
